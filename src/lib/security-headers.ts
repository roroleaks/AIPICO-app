/**
 * CORS allowed origins for API routes.
 *
 * Both origins are in active use:
 *   - aipico.vercel.app  — primary deployment (confirmed in results/reports/security_headers.txt, line 36)
 *   - aipico-app.vercel.app — secondary deployment (confirmed in results/reports/security_headers.txt, line 6)
 *
 * Their mapping to commits is [Unverified] pending the Vercel dashboard check (see 08_REPORT.md).
 * Vercel's own origin header is included unconditionally to cover preview deployments on the
 * same project (e.g. aipico-*.vercel.app). [Inference]
 *
 * localhost:3000 is included for local development only when NODE_ENV !== "production".
 * It is not emitted in production headers.
 */
export const ALLOWED_ORIGINS = [
  "https://aipico.vercel.app",
  "https://aipico-app.vercel.app",
];

/** Returns true when the request Origin header is in the allow-list. */
export function isAllowedOrigin(origin: string | null): boolean {
  if (!origin) return false;
  if (ALLOWED_ORIGINS.includes(origin)) return true;
  // Preview deployments on the same Vercel project share the aipico*.vercel.app namespace.
  if (/^https:\/\/aipico[a-z0-9-]*\.vercel\.app$/.test(origin)) return true;
  // Local development
  if (process.env.NODE_ENV !== "production" && origin === "http://localhost:3000") return true;
  return false;
}

/** CORS response headers for a matched origin. Returned as a plain object for use in NextResponse. */
export function corsHeaders(origin: string): Record<string, string> {
  return {
    "Access-Control-Allow-Origin": origin,
    "Access-Control-Allow-Methods": "POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type",
    "Access-Control-Max-Age": "86400",
    "Vary": "Origin",
  };
}
